-- Movie catalog stored in Supabase (replaces runtime calls to the TMDB API).
--
-- * genres          fixed list (TMDB genre ids and names), read-only
-- * movies          one row per movie; seeded movies keep their TMDB id so
--                   favorites, watchlist, ratings and reviews stay linked.
--                   Movies created in the app get ids from 100000000 up.
-- * movie_genres    movie ↔ genre
-- * movie_credits   directors and cast, ordered by position
--
-- Access: everyone reads; any signed-in user creates, edits and deletes
-- movies (project decision). created_by records who added a movie.
--
-- Deleting a movie keeps its ratings and reviews (they show as "removed
-- from the catalogue"); new ratings and reviews require an existing movie.
--
-- Seed data: supabase/seed/movies_seed.sql (100 movies).

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.genres (
  id smallint primary key,
  name text not null unique check (char_length(name) between 1 and 50)
);

create table if not exists public.movies (
  id integer generated by default as identity (start with 100000000) primary key,
  title text not null check (char_length(title) between 1 and 200),
  original_title text not null default '' check (char_length(original_title) <= 200),
  tagline text not null default '' check (char_length(tagline) <= 300),
  overview text not null default '' check (char_length(overview) <= 5000),
  release_date date,
  runtime integer check (runtime between 1 and 1000),
  original_language text check (original_language ~ '^[a-z]{2}$'),
  poster_url text check (poster_url ~ '^https://\S+$'),
  backdrop_url text check (backdrop_url ~ '^https://\S+$'),
  trailer_youtube_key text check (trailer_youtube_key ~ '^[A-Za-z0-9_-]{6,20}$'),
  vote_average numeric(3, 1) not null default 0 check (vote_average between 0 and 10),
  vote_count integer not null default 0 check (vote_count >= 0),
  popularity numeric(12, 3) not null default 0 check (popularity >= 0),
  status text not null default 'Released' check (
    status in ('Rumored', 'Planned', 'In Production', 'Post Production', 'Released', 'Canceled')
  ),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists movies_popularity_idx on public.movies (popularity desc);
create index if not exists movies_release_date_idx on public.movies (release_date);
create index if not exists movies_vote_average_idx on public.movies (vote_average desc);
create index if not exists movies_title_lower_idx on public.movies (lower(title));

create table if not exists public.movie_genres (
  movie_id integer not null references public.movies(id) on delete cascade,
  genre_id smallint not null references public.genres(id) on delete cascade,
  primary key (movie_id, genre_id)
);

create index if not exists movie_genres_genre_idx on public.movie_genres (genre_id);

create table if not exists public.movie_credits (
  id bigint generated always as identity primary key,
  movie_id integer not null references public.movies(id) on delete cascade,
  kind text not null check (kind in ('director', 'cast')),
  name text not null check (char_length(name) between 1 and 120),
  character text not null default '' check (char_length(character) <= 200),
  profile_url text check (profile_url ~ '^https://\S+$'),
  position smallint not null default 0
);

create index if not exists movie_credits_movie_idx
  on public.movie_credits (movie_id, kind, position);

