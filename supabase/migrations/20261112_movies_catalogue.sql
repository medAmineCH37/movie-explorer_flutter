create or replace function public.movies_before_write()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.title := public.trim_text(new.title);
  new.original_title := public.trim_text(coalesce(new.original_title, ''));
  new.tagline := public.trim_text(coalesce(new.tagline, ''));
  new.overview := public.trim_text(coalesce(new.overview, ''));

  if tg_op = 'INSERT' then
    new.created_by := coalesce(auth.uid(), new.created_by);
    new.created_at := now();
  else
    new.created_by := old.created_by;
    new.created_at := old.created_at;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists movies_before_write on public.movies;
create trigger movies_before_write
  before insert or update on public.movies
  for each row execute function public.movies_before_write();

-- New ratings and reviews must point to a movie of the catalogue.
create or replace function public.require_catalogue_movie()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (select 1 from public.movies m where m.id = new.tmdb_movie_id) then
    raise exception 'movie_not_found'
      using errcode = 'P0002', hint = 'This movie is not in the catalogue.';
  end if;
  return new;
end;
$$;

drop trigger if exists ratings_require_movie on public.ratings;
create trigger ratings_require_movie
  before insert on public.ratings
  for each row execute function public.require_catalogue_movie();

drop trigger if exists reviews_require_movie on public.reviews;
create trigger reviews_require_movie
  before insert on public.reviews
  for each row execute function public.require_catalogue_movie();

