-- ---------------------------------------------------------------------------
-- Write API: create or update a movie with its genres and credits atomically
-- ---------------------------------------------------------------------------

-- p_movie keys: title, original_title, tagline, overview, release_date
-- (YYYY-MM-DD), runtime, original_language, poster_url, backdrop_url,
-- trailer_youtube_key, vote_average, status. Empty strings mean "none".
-- p_cast: [{"name": "...", "character": "..."}]. Returns the movie id.
create or replace function public.save_movie(
  p_id integer,
  p_movie jsonb,
  p_genre_ids smallint[] default '{}',
  p_directors text[] default '{}',
  p_cast jsonb default '[]'
)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_id integer;
  v_old_profiles jsonb;
  v_directors text[] := array(
    select public.trim_text(d) from unnest(coalesce(p_directors, '{}')) d
    where public.trim_text(d) <> ''
  );
begin
  if auth.uid() is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;
  if cardinality(v_directors) > 10 then
    raise exception 'too_many_directors' using errcode = '22023';
  end if;
  if jsonb_typeof(coalesce(p_cast, '[]')) <> 'array'
     or jsonb_array_length(coalesce(p_cast, '[]')) > 30 then
    raise exception 'invalid_cast' using errcode = '22023';
  end if;

  if p_id is null then
    insert into public.movies (
      title, original_title, tagline, overview, release_date, runtime,
      original_language, poster_url, backdrop_url, trailer_youtube_key,
      vote_average, status
    ) values (
      p_movie->>'title',
      coalesce(p_movie->>'original_title', ''),
      coalesce(p_movie->>'tagline', ''),
      coalesce(p_movie->>'overview', ''),
      nullif(p_movie->>'release_date', '')::date,
      nullif(p_movie->>'runtime', '')::integer,
      nullif(lower(p_movie->>'original_language'), ''),
      nullif(public.trim_text(p_movie->>'poster_url'), ''),
      nullif(public.trim_text(p_movie->>'backdrop_url'), ''),
      nullif(public.trim_text(p_movie->>'trailer_youtube_key'), ''),
      coalesce(nullif(p_movie->>'vote_average', '')::numeric, 0),
      coalesce(nullif(p_movie->>'status', ''), 'Released')
    )
    returning id into v_id;
  else
    update public.movies set
      title = p_movie->>'title',
      original_title = coalesce(p_movie->>'original_title', ''),
      tagline = coalesce(p_movie->>'tagline', ''),
      overview = coalesce(p_movie->>'overview', ''),
      release_date = nullif(p_movie->>'release_date', '')::date,
      runtime = nullif(p_movie->>'runtime', '')::integer,
      original_language = nullif(lower(p_movie->>'original_language'), ''),
      poster_url = nullif(public.trim_text(p_movie->>'poster_url'), ''),
      backdrop_url = nullif(public.trim_text(p_movie->>'backdrop_url'), ''),
      trailer_youtube_key = nullif(public.trim_text(p_movie->>'trailer_youtube_key'), ''),
      vote_average = coalesce(nullif(p_movie->>'vote_average', '')::numeric, 0),
      status = coalesce(nullif(p_movie->>'status', ''), 'Released')
    where id = p_id
    returning id into v_id;

    if v_id is null then
      raise exception 'movie_not_found' using errcode = 'P0002';
    end if;
  end if;

  delete from public.movie_genres where movie_id = v_id;
  insert into public.movie_genres (movie_id, genre_id)
  select distinct v_id, g from unnest(coalesce(p_genre_ids, '{}')) g;

  -- Credits are replaced as a whole; profile pictures of kept names survive.
  select coalesce(jsonb_agg(jsonb_build_object(
           'name', c.name, 'kind', c.kind, 'url', c.profile_url)), '[]')
  into v_old_profiles
  from public.movie_credits c
  where c.movie_id = v_id and c.profile_url is not null;

  delete from public.movie_credits where movie_id = v_id;

  insert into public.movie_credits (movie_id, kind, name, position, profile_url)
  select v_id, 'director', d.name, d.ord - 1,
    (select o->>'url' from jsonb_array_elements(v_old_profiles) o
     where o->>'name' = d.name and o->>'kind' = 'director' limit 1)
  from unnest(v_directors) with ordinality as d(name, ord);

  insert into public.movie_credits (movie_id, kind, name, character, position, profile_url)
  select v_id, 'cast',
    public.trim_text(c.value->>'name'),
    public.trim_text(coalesce(c.value->>'character', '')),
    c.ord - 1,
    (select o->>'url' from jsonb_array_elements(v_old_profiles) o
     where o->>'name' = public.trim_text(c.value->>'name') and o->>'kind' = 'cast'
     limit 1)
  from jsonb_array_elements(coalesce(p_cast, '[]')) with ordinality as c(value, ord)
  where public.trim_text(coalesce(c.value->>'name', '')) <> '';

  return v_id;
end;
$$;

