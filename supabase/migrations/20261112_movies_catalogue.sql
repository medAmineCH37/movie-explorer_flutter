-- Catalogue lists and Discovery search in one function.
--   p_category: popular | top_rated | now_playing | upcoming | null
--   p_sort:     popularity | rating | newest | oldest | title | null
--               (null = the category's natural order, else popularity)
-- Genres match if the movie has ANY of p_genre_ids. total_count repeats the
-- number of matching movies.
create or replace function public.search_movies(
  p_query text default null,
  p_genre_ids smallint[] default null,
  p_year_from integer default null,
  p_year_to integer default null,
  p_min_rating numeric default null,
  p_language text default null,
  p_category text default null,
  p_sort text default null,
  p_page integer default 1,
  p_page_size integer default 20
)
returns table (
  id integer,
  title text,
  overview text,
  release_date date,
  runtime integer,
  original_language text,
  poster_url text,
  backdrop_url text,
  vote_average numeric,
  vote_count integer,
  popularity numeric,
  genres text[],
  total_count bigint
)
language plpgsql
stable
security invoker
set search_path = ''
as $$
#variable_conflict use_column
declare
  page_size integer := least(greatest(coalesce(p_page_size, 20), 1), 100);
  page_number integer := greatest(coalesce(p_page, 1), 1);
  sort text := coalesce(
    p_sort,
    case p_category
      when 'top_rated' then 'rating'
      when 'upcoming' then 'soonest'
      else 'popularity'
    end
  );
  pattern text := case
    when nullif(public.trim_text(coalesce(p_query, '')), '') is null then null
    else '%' || replace(replace(replace(public.trim_text(p_query), '\', '\\'), '%', '\%'), '_', '\_') || '%'
  end;
begin
  if p_category is not null
     and p_category not in ('popular', 'top_rated', 'now_playing', 'upcoming') then
    raise exception 'unknown category %', p_category;
  end if;
  if sort not in ('popularity', 'rating', 'newest', 'oldest', 'soonest', 'title') then
    raise exception 'unknown sort %', sort;
  end if;

  return query
  select
    m.id, m.title, m.overview, m.release_date, m.runtime, m.original_language,
    m.poster_url, m.backdrop_url, m.vote_average, m.vote_count, m.popularity,
    coalesce(
      (select array_agg(g.name order by g.name)
       from public.movie_genres mg join public.genres g on g.id = mg.genre_id
       where mg.movie_id = m.id),
      '{}'
    ),
    count(*) over ()
  from public.movies m
  where (pattern is null or m.title ilike pattern or m.original_title ilike pattern)
    and (p_genre_ids is null or cardinality(p_genre_ids) = 0 or exists (
      select 1 from public.movie_genres mg
      where mg.movie_id = m.id and mg.genre_id = any(p_genre_ids)
    ))
    and (p_year_from is null or extract(year from m.release_date) >= p_year_from)
    and (p_year_to is null or extract(year from m.release_date) <= p_year_to)
    and (p_min_rating is null or m.vote_average >= p_min_rating)
    and (p_language is null or m.original_language = lower(p_language))
    and (
      p_category is null
      or p_category = 'popular'
      or (p_category = 'top_rated' and m.vote_count >= 50)
      or (p_category = 'now_playing'
          and m.release_date between current_date - 60 and current_date)
      or (p_category = 'upcoming' and m.release_date > current_date)
    )
  order by
    case when sort = 'popularity' then m.popularity end desc nulls last,
    case when sort = 'rating' then m.vote_average end desc nulls last,
    case when sort = 'rating' then m.vote_count end desc nulls last,
    case when sort = 'newest' then m.release_date end desc nulls last,
    case when sort in ('oldest', 'soonest') then m.release_date end asc nulls last,
    case when sort = 'title' then lower(m.title) end asc,
    m.id
  limit page_size
  offset (page_number - 1) * page_size;
end;
$$;

-- Languages present in the catalogue, most frequent first (Discovery filter).
create or replace function public.movie_languages()
returns table (code text, movie_count bigint)
language sql
stable
security invoker
set search_path = ''
as $$
  select m.original_language, count(*)
  from public.movies m
  where m.original_language is not null
  group by m.original_language
  order by count(*) desc, m.original_language;
$$;

